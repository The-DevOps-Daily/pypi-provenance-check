ROUTES["https://pypi.org/pypi/requests/2.34.2/json"]["urls"].append(
    {"filename": "requests-2.34.2.tar.gz", "digests": {"sha256": "e" * 64}})
ROUTES["https://pypi.org/pypi/requests/2.34.2/json"]["urls"][0]["core-metadata"] = {"sha256": "PLACEHOLDER"}


def run(*argv):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        code = pc.main(list(argv), http=FakeHttp(ROUTES))
    return code, out.getvalue()


class TestHelpers(unittest.TestCase):
    def test_repo_from_url(self):
        self.assertEqual(pc.repo_from_url("https://github.com/PSF/Requests/tree/main"), "github.com/psf/requests")
        self.assertEqual(pc.repo_from_url("https://www.github.com/a/b.git"), "github.com/a/b")
        self.assertEqual(pc.repo_from_url("https://gitlab.com/g/sub/proj/-/issues"), "gitlab.com/g/sub/proj")
        self.assertIsNone(pc.repo_from_url("https://docs.example.com/a/b"))
        self.assertIsNone(pc.repo_from_url("https://github.com/onlyowner"))

    def test_wheel_tags(self):
        tags = pc.wheel_tags_from_filename("x-1.0-cp312-cp312-manylinux_2_17_x86_64.manylinux2014_x86_64.whl")
        self.assertEqual(tags, {"cp312-cp312-manylinux_2_17_x86_64", "cp312-cp312-manylinux2014_x86_64"})

    def test_lock_entries_requirements_hashes(self):
        tmp = tempfile.mkdtemp()
        try:
            p = os.path.join(tmp, "requirements.txt")
            with open(p, "w") as f:
                f.write("requests==2.34.2 \\\n    --hash=sha256:" + "c" * 64 + "\n")
            e = pc.lock_entries(p)
            self.assertEqual(e[0]["hashes"], ["c" * 64])
        finally:
            shutil.rmtree(tmp)

    def test_rye_requirements_lock(self):
        tmp = tempfile.mkdtemp()
        try:
            p = os.path.join(tmp, "requirements.lock")
            with open(p, "w") as f:
                f.write("# generated by rye\nrequests==2.34.2\n")
            self.assertEqual(pc.lock_entries(p)[0]["version"], "2.34.2")
        finally:
            shutil.rmtree(tmp)


class TestVerdicts(unittest.TestCase):
    def test_litellm_history(self):
        code, out = run("--package", "litellm==1.83.14", "--package", "litellm==1.106.2", "--package", "litellm==1.107.0")
        self.assertEqual(code, 1)  # 1.107.0 is not on PyPI
        self.assertRegex(out, r"litellm==1\.83\.14\s+attested-other-repo .*BerriAI/project-releaser")
        self.assertRegex(out, r"litellm==1\.106\.2\s+no-attestation")
        self.assertRegex(out, r"litellm==1\.107\.0\s+not-on-pypi")

    def test_match_by_wheel_hash(self):
        tmp = tempfile.mkdtemp()
        try:
            p = os.path.join(tmp, "requirements.txt")
            with open(p, "w") as f:
                f.write("requests==2.34.2 --hash=sha256:" + "c" * 64 + "\n")
            code, out = run("--lock", p, "--require-repo-match")
            self.assertEqual(code, 0, out)
            self.assertIn("attested-match", out)
        finally:
            shutil.rmtree(tmp)

    def test_bare_pin_checks_every_file(self):
        code, out = run("--package", "requests==2.34.2", "--require-attestation")
        self.assertEqual(code, 3, out)
        self.assertIn("partly-attested", out)
        self.assertIn("1 of 2 files attested", out)

    def test_one_unknown_hash_among_known_ones(self):
        tmp = tempfile.mkdtemp()
        try:
            p = os.path.join(tmp, "requirements.txt")
            with open(p, "w") as f:
                f.write("requests==2.34.2 --hash=sha256:" + "c" * 64 + " --hash=sha256:" + "d" * 64 + "\n")
            code, out = run("--lock", p)
            self.assertEqual(code, 1, out)
            self.assertIn("1 of 2 hash(es)", out)
        finally:
            shutil.rmtree(tmp)

    def test_pins_file_must_exist(self):
        with self.assertRaises(SystemExit) as cm:
            run("--package", "requests==2.34.2", "--pins", "/nonexistent/pins.json")
        self.assertEqual(cm.exception.code, 2)

    def test_require_attestation(self):
        code, _ = run("--package", "litellm==1.106.2", "--require-attestation")
        self.assertEqual(code, 3)

    def test_require_repo_match_fails_on_other_repo(self):
        code, _ = run("--package", "litellm==1.83.14", "--require-repo-match")
        self.assertEqual(code, 3)

    def test_hash_not_on_pypi(self):
        tmp = tempfile.mkdtemp()
        try:
            p = os.path.join(tmp, "requirements.txt")
            with open(p, "w") as f:
                f.write("requests==2.34.2 --hash=sha256:" + "d" * 64 + "\n")
            code, out = run("--lock", p)
            self.assertEqual(code, 1)
            self.assertIn("hash-not-on-pypi", out)
        finally:
            shutil.rmtree(tmp)

    def test_installed_env_matches_wheel_by_tags(self):
        tmp = tempfile.mkdtemp()
        try:
            sp = os.path.join(tmp, "lib/python3.12/site-packages")
            fixtures.install_like_pip(sp, name="requests", version="2.34.2", payload=False)
            with open(os.path.join(sp, "requests-2.34.2.dist-info", "METADATA"), "rb") as f:
                digest = hashlib.sha256(f.read()).hexdigest()
            ROUTES["https://pypi.org/pypi/requests/2.34.2/json"]["urls"][0]["core-metadata"] = {"sha256": digest}
            code, out = run("--env", tmp)
            self.assertEqual(code, 0, out)
            self.assertIn("attested-match", out)
        finally:
            shutil.rmtree(tmp)

    def test_installed_metadata_differs(self):
        tmp = tempfile.mkdtemp()
        try:
            sp = os.path.join(tmp, "site-packages")
            fixtures.install_like_pip(sp, name="requests", version="2.34.2", payload=False)
            ROUTES["https://pypi.org/pypi/requests/2.34.2/json"]["urls"][0]["core-metadata"] = {"sha256": "0" * 64}
            code, out = run("--env", sp)
            self.assertEqual(code, 1, out)
            self.assertIn("metadata-differs", out)
        finally:
            shutil.rmtree(tmp)

    def test_installed_without_pypi_metadata_hash_is_unknown(self):
        tmp = tempfile.mkdtemp()
        try:
            sp = os.path.join(tmp, "site-packages")
            fixtures.install_like_pip(sp, name="requests", version="2.34.2", payload=False)
            ROUTES["https://pypi.org/pypi/requests/2.34.2/json"]["urls"][0].pop("core-metadata", None)
            code, out = run("--env", sp, "--require-attestation")
            self.assertEqual(code, 3, out)
            self.assertIn("file-unknown", out)
        finally:
            shutil.rmtree(tmp)

    def test_two_copies_with_different_metadata_are_both_checked(self):
        tmp = tempfile.mkdtemp()
        try:
            a = os.path.join(tmp, "a", "site-packages")
            b = os.path.join(tmp, "b", "site-packages")
            fixtures.install_like_pip(a, name="requests", version="2.34.2", payload=False)
            fixtures.install_like_pip(b, name="requests", version="2.34.2", payload=False)
            with open(os.path.join(b, "requests-2.34.2.dist-info", "METADATA"), "a") as f:
                f.write("X-Changed: yes\n")
            with open(os.path.join(a, "requests-2.34.2.dist-info", "METADATA"), "rb") as f:
                good = hashlib.sha256(f.read()).hexdigest()
            ROUTES["https://pypi.org/pypi/requests/2.34.2/json"]["urls"][0]["core-metadata"] = {"sha256": good}
            code, out = run("--env", a, "--env", b)
            self.assertEqual(code, 1, out)
            self.assertIn("metadata-differs", out)
            self.assertIn("attested-match", out)
        finally:
            shutil.rmtree(tmp)

    def test_require_attestation_rejects_unknown_file(self):
        tmp = tempfile.mkdtemp()
        try:
            sp = os.path.join(tmp, "site-packages")
            fixtures.install_like_pip(sp, name="litellm", version="1.106.2", payload=False)
            code, out = run("--env", sp, "--require-attestation")
            self.assertEqual(code, 3, out)
        finally:
            shutil.rmtree(tmp)

    def test_installed_wheel_with_unknown_tags(self):
        tmp = tempfile.mkdtemp()
        try:
            sp = os.path.join(tmp, "site-packages")
            fixtures.install_like_pip(sp, name="litellm", version="1.106.2", payload=False)
            code, out = run("--env", sp)
            self.assertIn("file-unknown", out)  # fixture is py3-none-any, PyPI only has abi3 wheels
        finally:
            shutil.rmtree(tmp)

    def test_pins(self):
        tmp = tempfile.mkdtemp()
        try:
            pins = os.path.join(tmp, "pins.json")
            code, _ = run("--package", "litellm==1.83.14", "--write-pins", pins)
            self.assertEqual(code, 0)
            code, out = run("--package", "litellm==1.106.2", "--pins", pins)
            self.assertEqual(code, 1)
            self.assertIn("PIN CHANGED", out)
            # a pinned project that this run cannot confirm also alerts
            code, out = run("--package", "litellm==1.107.0", "--pins", pins)
            self.assertEqual(code, 1)
        finally:
            shutil.rmtree(tmp)


